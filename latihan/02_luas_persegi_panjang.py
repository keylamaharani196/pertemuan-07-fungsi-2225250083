
# Latihan 2: Luas Persegi Panjang

def luas_persegi_panjang(p, l):
    return p * l


# Test case 1
print("Panjang = 8, Lebar = 5")
print("Luas persegi panjang =", luas_persegi_panjang(8, 5))

# Test case 2
print("Panjang = 2.5, Lebar = 4")
print("Luas persegi panjang =", luas_persegi_panjang(2.5, 4))

# Test case 3
print("Panjang = 0, Lebar = 7")
print("Luas persegi panjang =", luas_persegi_panjang(0, 7))
